#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(i8)]
pub enum FadeState {
    FadeIn = -1,
    Complete = 0,
    FadeOut = 1,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(i8)]
pub enum SubFadeState {
    Start = -1,
    Fading = 0,
    Complete = 1,
}

/// The six ordered timeline loops in `AnimationState.advanceTime` after the
/// action and z-order timelines have run.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TimelineGroup {
    Bone,
    BoneBlend,
    Slot,
    SlotBlend,
    Constraint,
    Animation,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TimelineDirty {
    Clean,
    RefreshTargets,
    RebuildAll,
}

pub const TIMELINE_GROUP_UPDATE_ORDER: [TimelineGroup; 6] = [
    TimelineGroup::Bone,
    TimelineGroup::BoneBlend,
    TimelineGroup::Slot,
    TimelineGroup::SlotBlend,
    TimelineGroup::Constraint,
    TimelineGroup::Animation,
];

/// The official playhead is a two-bit value: bit 0 enables play after fade-in,
/// bit 1 permits play. Only `PLAYING` (3) advances animation time.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PlayheadState(u8);

impl PlayheadState {
    pub const STOPPED: Self = Self(0);
    pub const FADE_PAUSED: Self = Self(2);
    pub const PLAYING: Self = Self(3);

    #[must_use]
    pub const fn bits(self) -> u8 {
        self.0
    }

    #[must_use]
    pub const fn advances(self) -> bool {
        self.0 == Self::PLAYING.0
    }

    #[must_use]
    pub const fn is_playing(self) -> bool {
        self.0 & 2 != 0
    }

    pub fn play(&mut self) {
        self.0 = Self::PLAYING.0;
    }

    pub fn stop(&mut self) {
        self.0 &= 1;
    }

    pub fn pause_for_fade_out(&mut self) {
        self.0 &= 2;
    }

    pub fn enable_after_fade_in(&mut self) {
        self.0 |= 1;
    }
}

/// Lifecycle events generated by the fade state machine. Listener gating and
/// conversion to EventObject are performed by the owning Animation/Armature.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FadeEvent {
    FadeIn,
    FadeInComplete,
    FadeOut,
    FadeOutComplete,
}

impl FadeEvent {
    #[must_use]
    pub const fn event_type(self) -> &'static str {
        match self {
            Self::FadeIn => crate::event::EventObject::FADE_IN,
            Self::FadeInComplete => crate::event::EventObject::FADE_IN_COMPLETE,
            Self::FadeOut => crate::event::EventObject::FADE_OUT,
            Self::FadeOutComplete => crate::event::EventObject::FADE_OUT_COMPLETE,
        }
    }
}

