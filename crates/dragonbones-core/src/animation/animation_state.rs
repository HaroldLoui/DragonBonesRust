impl AnimationState {
    /// Copies playback fields from config/data. Timeline construction is a later task.
    pub fn init(
        &mut self,
        armature: ArmatureIdx,
        animation: &AnimationData,
        config: &AnimationConfig,
    ) {
        // AnimationState.ts:726-728：`_armature !== null` 时重复 init 直接忽略。
        // Rust 以 armature 绑定作为"已初始化"信号；StateArena 复用槽位时由
        // `Animation::play_config` 传入 Default 新值（对齐 `_onClear` 默认值）。
        if self.armature.is_some() {
            return;
        }
        self.armature = Some(armature);
        self.animation_name.clone_from(&animation.name);
        self.name = if config.name.is_empty() {
            animation.name.clone()
        } else {
            config.name.clone()
        };
        self.group.clone_from(&config.group);
        self.reset_to_pose = config.reset_to_pose;
        self.additive = config.additive;
        self.display_control = config.display_control;
        self.action_enabled = config.action_enabled;
        self.blend_type = animation.blend_type;
        self.layer = config.layer;
        self.play_times = config.play_times;
        self.time_scale = config.time_scale;
        self.fade_total_time = config.fade_in_time;
        self.auto_fade_out_time = config.auto_fade_out_time;
        self.weight = config.weight;
        self.playhead_state = if config.pause_fade_in {
            PlayheadState::FADE_PAUSED
        } else {
            PlayheadState::PLAYING
        };

        if config.duration < 0.0 {
            self.position = 0.0;
            self.duration = animation.duration;
            self.time = if config.position != 0.0 {
                if self.time_scale >= 0.0 {
                    config.position
                } else {
                    config.position - self.duration
                }
            } else {
                0.0
            };
        } else {
            self.position = config.position;
            self.duration = config.duration;
            self.time = 0.0;
        }

        if self.time_scale < 0.0 && self.time == 0.0 {
            self.time = -0.000001;
        }
        if self.fade_total_time <= 0.0 {
            self.fade_progress = 0.999999;
        }
        if !config.bone_mask.is_empty() {
            self.bone_mask.clone_from(&config.bone_mask);
        }
        self.timeline_dirty = TimelineDirty::RebuildAll;
    }

    pub fn play(&mut self) {
        self.playhead_state.play();
    }

    pub fn stop(&mut self) {
        self.playhead_state.stop();
    }

    /// Updates fade progress and returns lifecycle event kinds in enqueue order.
    pub fn advance_fade_time(&mut self, passed_time: f64) -> Vec<FadeEvent> {
        let is_fade_out = self.fade_state == FadeState::FadeOut;
        let mut events = Vec::with_capacity(2);

        if self.sub_fade_state == SubFadeState::Start {
            self.sub_fade_state = SubFadeState::Fading;
            events.push(if is_fade_out {
                FadeEvent::FadeOut
            } else {
                FadeEvent::FadeIn
            });
        }

        let passed_time = if passed_time < 0.0 {
            -passed_time
        } else {
            passed_time
        };
        self.fade_time += passed_time;

        if self.fade_time >= self.fade_total_time {
            self.sub_fade_state = SubFadeState::Complete;
            self.fade_progress = if is_fade_out { 0.0 } else { 1.0 };
        } else if self.fade_time > 0.0 {
            self.fade_progress = if is_fade_out {
                1.0 - self.fade_time / self.fade_total_time
            } else {
                self.fade_time / self.fade_total_time
            };
        } else {
            self.fade_progress = if is_fade_out { 1.0 } else { 0.0 };
        }

        if self.sub_fade_state == SubFadeState::Complete {
            if !is_fade_out {
                self.playhead_state.enable_after_fade_in();
                self.fade_state = FadeState::Complete;
            }
            events.push(if is_fade_out {
                FadeEvent::FadeOutComplete
            } else {
                FadeEvent::FadeInComplete
            });
        }

        events
    }

    /// Starts or retimes a fade-out. Returns `true` only when this call entered
    /// the first-fade-out branch (TS `AnimationState.ts:1125-1159`); the guard
    /// return at `:1120-1123` yields `false` and must not cascade to children.
    pub fn fade_out(&mut self, mut fade_out_time: f64, pause_playhead: bool) -> bool {
        if fade_out_time < 0.0 {
            fade_out_time = 0.0;
        }

        if pause_playhead {
            self.playhead_state.pause_for_fade_out();
        }

        let mut began_fade_out = false;
        if self.fade_state == FadeState::FadeOut {
            if fade_out_time > self.fade_total_time - self.fade_time {
                // AnimationState.ts:1120-1123：已在淡出且新时长更长 → 整体忽略。
                return false;
            }
        } else {
            // AnimationState.ts:1125-1159：只有首次进入淡出才清 timeline dirty
            // 并级联子状态的 999999 淡出；已在淡出时重定时不得重复执行。
            began_fade_out = true;
            self.fade_state = FadeState::FadeOut;
            self.sub_fade_state = SubFadeState::Start;
            if fade_out_time <= 0.0 || self.fade_progress <= 0.0 {
                self.fade_progress = 0.000001;
            }
            for group in TIMELINE_GROUP_UPDATE_ORDER {
                for timeline in self.timeline_group_mut(group) {
                    timeline.fade_out();
                }
            }
        }
        // AnimationState.ts:1161-1163：guard 通过后无论是否首次淡出都会执行。
        self.display_control = false;
        self.fade_total_time = if self.fade_progress > 0.000001 {
            fade_out_time / self.fade_progress
        } else {
            0.0
        };
        self.fade_time = self.fade_total_time * (1.0 - self.fade_progress);
        began_fade_out
    }

    /// Advances state time only when both playhead bits are enabled.
    pub fn advance_playhead(&mut self, passed_time: f64) {
        if self.playhead_state.advances() {
            if self.time_scale != 1.0 {
                self.time += passed_time * self.time_scale;
            } else {
                self.time += passed_time;
            }
        }
    }

    pub(crate) fn set_current_time(&mut self, mut value: f64) {
        let current_play_times = self.current_play_times
            - if self.action_play_state > TimelinePlayState::Play {
                1
            } else {
                0
            };
        if value < 0.0 || self.duration < value {
            value = (value % self.duration) + f64::from(current_play_times) * self.duration;
            if value < 0.0 {
                value += self.duration;
            }
        }
        if self.play_times > 0
            && current_play_times == self.play_times - 1
            && value == self.duration
            && self.parent.is_none()
        {
            value = self.duration - 0.000001;
        }
        if self.time == value {
            return;
        }

        self.time = value;
        if let Some(action) = self.action_timeline.as_mut() {
            action.base.current_time = value;
            action.base.frame_index = -1;
        }
        if let Some(z_order) = self.z_order_timeline.as_mut() {
            z_order.base.play_state = TimelinePlayState::Start;
            z_order.base.frame_index = -1;
        }
        for timeline in &mut self.bone_timelines {
            timeline.base.play_state = TimelinePlayState::Start;
            timeline.base.frame_index = -1;
        }
        for timeline in &mut self.slot_timelines {
            timeline.base.play_state = TimelinePlayState::Start;
            timeline.base.frame_index = -1;
        }
    }

    /// Applies the fade-before-playhead portion of `advanceTime` and computes
    /// this state's provisional blend weight. Timeline/action groups run after it.
    pub(crate) fn advance_time(
        &mut self,
        passed_time: f64,
        parent_weight_result: f64,
    ) -> Vec<FadeEvent> {
        let mut events = Vec::new();
        if self.fade_state != FadeState::Complete || self.sub_fade_state != SubFadeState::Fading {
            events = self.advance_fade_time(passed_time);
        }

        self.advance_playhead(passed_time);
        self.weight_result = self.weight * self.fade_progress * parent_weight_result;
        events
    }

    pub(crate) fn advance_time_with_context(
        &mut self,
        passed_time: f64,
        parent_weight_result: f64,
        context: &mut AnimationUpdateCtx<'_>,
        runtime: &mut RuntimeCtx<'_>,
        cache_frame_rate: f64,
        blend_states: &mut HashMap<BlendStateKey, BlendState>,
    ) -> Vec<FadeEvent> {
        let fade_events = self.advance_time(passed_time, parent_weight_result);
        let event_active = self.parent.is_none() && self.action_enabled;
        if event_active {
            for event in &fade_events {
                let event_type = event.event_type();
                if context.proxy.has_db_event_listener(event_type) {
                    context.buffer_lifecycle_event(runtime, event_type);
                }
            }
        }

        if self.timeline_dirty != TimelineDirty::Clean {
            super::timeline_states::rebuild::rebuild(self, context, blend_states);
        }

        if let Some(mut action_timeline) = self.action_timeline.take() {
            if action_timeline.base.play_state <= TimelinePlayState::Play {
                super::timeline_states::action::update_action_timeline(
                    &mut action_timeline,
                    self,
                    context,
                    runtime,
                );
            }
            self.action_play_state = action_timeline.base.play_state;
            self.current_play_times = action_timeline.base.current_play_times;
            self.action_timeline = Some(action_timeline);
        }

        // Official ActionTimelineState runs before the zero-weight early return.
        if self.weight == 0.0 {
            return Vec::new();
        }

        let is_cache_enabled = self.fade_state == FadeState::Complete && cache_frame_rate > 0.0;

        // AnimationState.ts:850-852：先量化 action.currentTime，再更新 zOrder。
        if is_cache_enabled {
            let cache_interval = cache_frame_rate * 2.0;
            if let Some(action_timeline) = self.action_timeline.as_mut() {
                action_timeline.base.current_time =
                    (action_timeline.base.current_time * cache_interval).floor() / cache_interval;
            }
        }

        // AnimationState.ts:855-857：zOrder 读取的是已量化的 currentTime。
        if let Some(mut z_order_timeline) = self.z_order_timeline.take() {
            if z_order_timeline.base.play_state <= TimelinePlayState::Play {
                super::timeline_states::z_order::update_z_order_timeline(
                    &mut z_order_timeline,
                    self,
                    context,
                );
            }
            self.z_order_timeline = Some(z_order_timeline);
        }

        // AnimationState.ts:859-866：缓存帧判定保持在 zOrder 更新之后。
        let mut update_timelines = true;
        if is_cache_enabled && let Some(action_timeline) = self.action_timeline.as_ref() {
            let cache_frame_index =
                (action_timeline.base.current_time * cache_frame_rate).floor() as i32;
            if *context.cache_frame_index == cache_frame_index {
                update_timelines = false;
            } else {
                *context.cache_frame_index = cache_frame_index;
            }
        }

        if update_timelines {
            let action_time = self
                .action_timeline
                .as_ref()
                .map(|timeline| ActionTimelineTime {
                    play_state: timeline.base.play_state,
                    current_play_times: timeline.base.current_play_times,
                    current_time: timeline.base.current_time,
                });
            super::timeline_states::update::update_groups(self, context, blend_states, action_time);
        }

        self.finish_advance();
        Vec::new()
    }

    /// Performs the fade-complete cleanup at the tail of the state update,
    /// after timeline/pose processing has observed `SubFadeState::Complete`.
    pub(crate) fn finish_advance(&mut self) {
        if self.fade_state == FadeState::Complete && self.sub_fade_state == SubFadeState::Complete {
            self.remove_pose_timelines();
            self.sub_fade_state = SubFadeState::Fading;
        }
        if self.fade_state == FadeState::Complete
            && self.action_play_state > TimelinePlayState::Play
            && self.auto_fade_out_time >= 0.0
        {
            self.fade_out(self.auto_fade_out_time, true);
        }
    }

    pub(crate) fn push_timeline(
        &mut self,
        group: TimelineGroup,
        mut timeline: TimelineInstance,
        is_pose: bool,
    ) -> u32 {
        let id = self.next_timeline_id;
        self.next_timeline_id = self
            .next_timeline_id
            .checked_add(1)
            .expect("AnimationState exhausted timeline IDs");
        timeline.id = id;
        timeline.is_pose = is_pose;
        if is_pose {
            self.pose_timeline_ids.push(id);
        }
        self.timeline_group_mut(group).push(timeline);
        id
    }

    pub(crate) fn timeline_group_mut(
        &mut self,
        group: TimelineGroup,
    ) -> &mut Vec<TimelineInstance> {
        match group {
            TimelineGroup::Bone => &mut self.bone_timelines,
            TimelineGroup::BoneBlend => &mut self.bone_blend_timelines,
            TimelineGroup::Slot => &mut self.slot_timelines,
            TimelineGroup::SlotBlend => &mut self.slot_blend_timelines,
            TimelineGroup::Constraint => &mut self.constraint_timelines,
            TimelineGroup::Animation => &mut self.animation_timelines,
        }
    }

    pub(crate) fn mark_timelines_for_refresh(&mut self) {
        if self.timeline_dirty == TimelineDirty::Clean {
            self.timeline_dirty = TimelineDirty::RefreshTargets;
        }
    }

    fn remove_pose_timelines(&mut self) {
        if self.pose_timeline_ids.is_empty() {
            return;
        }
        let pose_ids: HashSet<_> = self.pose_timeline_ids.iter().copied().collect();
        for group in TIMELINE_GROUP_UPDATE_ORDER {
            self.timeline_group_mut(group)
                .retain(|timeline| !pose_ids.contains(&timeline.id));
        }
        self.pose_timeline_ids.clear();
    }

    #[must_use]
    pub fn is_playing(&self) -> bool {
        let play_state = self
            .action_timeline
            .as_ref()
            .map_or(self.action_play_state, |timeline| timeline.base.play_state);
        self.playhead_state.is_playing() && play_state <= TimelinePlayState::Play
    }

    #[must_use]
    pub fn is_completed(&self) -> bool {
        self.action_timeline.as_ref().map_or(
            self.action_play_state > TimelinePlayState::Play,
            |timeline| timeline.base.play_state > TimelinePlayState::Play,
        )
    }

    #[must_use]
    pub fn is_fade_in(&self) -> bool {
        self.fade_state == FadeState::FadeIn
    }

    #[must_use]
    pub fn is_fade_out(&self) -> bool {
        self.fade_state == FadeState::FadeOut
    }

    #[must_use]
    pub fn is_fade_complete(&self) -> bool {
        self.fade_state == FadeState::Complete
    }

    #[must_use]
    pub fn current_time(&self) -> f64 {
        self.action_timeline
            .as_ref()
            .map_or(self.time, |timeline| timeline.base.current_time)
    }

    #[must_use]
    pub fn total_time(&self) -> f64 {
        self.duration
    }

    #[must_use]
    pub fn current_play_times(&self) -> i32 {
        self.action_timeline
            .as_ref()
            .map_or(self.current_play_times, |timeline| {
                timeline.base.current_play_times
            })
    }

    pub fn set_weight(&mut self, weight: f64) {
        if self.weight == weight {
            return;
        }
        self.weight = weight;
        // AnimationState.ts:1496-1513：权重变化只标记 bone/boneBlend/slotBlend
        // 三组 timeline dirty，不触碰 slot（直接写）与 animation（子状态）组。
        for timeline in &mut self.bone_timelines {
            timeline.base.dirty = true;
        }
        for timeline in &mut self.bone_blend_timelines {
            timeline.base.dirty = true;
        }
        for timeline in &mut self.slot_blend_timelines {
            timeline.base.dirty = true;
        }
    }

    #[must_use]
    pub fn contains_bone_mask(&self, bone_name: &str) -> bool {
        self.bone_mask.is_empty() || self.bone_mask.iter().any(|name| name == bone_name)
    }

    pub fn add_bone_mask(&mut self, bone_name: &str, recursive: bool, bones: &[Bone]) {
        let Some(bone) = bones.iter().find(|bone| bone.bone_name == bone_name) else {
            return;
        };
        if !self.bone_mask.iter().any(|name| name == bone_name) {
            self.bone_mask.push(bone_name.to_owned());
        }

        if recursive {
            for child in bones {
                if !self.bone_mask.iter().any(|name| name == &child.bone_name)
                    && bone.contains(bones, child.idx)
                {
                    self.bone_mask.push(child.bone_name.clone());
                }
            }
        }
        self.mark_timelines_for_refresh();
    }

    pub fn remove_bone_mask(&mut self, bone_name: &str, recursive: bool, bones: &[Bone]) {
        if let Some(index) = self.bone_mask.iter().position(|name| name == bone_name) {
            self.bone_mask.remove(index);
        }

        if recursive && let Some(bone) = bones.iter().find(|bone| bone.bone_name == bone_name) {
            if !self.bone_mask.is_empty() {
                let mut index = 0;
                while index < self.bone_mask.len() {
                    let remove = bones
                        .iter()
                        .find(|candidate| candidate.bone_name == self.bone_mask[index])
                        .is_some_and(|candidate| bone.contains(bones, candidate.idx));
                    if remove {
                        self.bone_mask.remove(index);
                    } else {
                        index += 1;
                    }
                }
            } else {
                for candidate in bones {
                    if candidate.idx != bone.idx && !bone.contains(bones, candidate.idx) {
                        self.bone_mask.push(candidate.bone_name.clone());
                    }
                }
            }
        }

        self.mark_timelines_for_refresh();
    }

    pub fn remove_all_bone_mask(&mut self) {
        self.bone_mask.clear();
        self.mark_timelines_for_refresh();
    }
}

