        // slotBlend（zIndex）。类型本身不影响 dirty 契约。
        state.push_timeline(TimelineGroup::Bone, timeline.clone(), true);
        state.push_timeline(TimelineGroup::BoneBlend, timeline.clone(), false);
        state.push_timeline(TimelineGroup::SlotBlend, timeline, false);

